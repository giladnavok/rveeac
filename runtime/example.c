#include "accel.h"
#include <stdio.h>
#include "utility.h"

#define N 10

uint8_t key[16] = { 0x2b,0x7e,0x15,0x16,0x28,0xae,0xd2,0xa6,0xab,0xf7,0x15,0x88,0x09,0xcf,0x4f,0x3c };
uint8_t pts [N][16] = {
	{0x32,0x43,0xf6,0xa8,0x88,0x5a,0x30,0x8d,0x31,0x31,0x98,0xa2,0xe0,0x37,0x07,0x11},
	{0x33,0x43,0xf6,0xa8,0x88,0x5a,0x30,0x8d,0x31,0x31,0x98,0xa2,0xe0,0x37,0x07,0x11},
	{0x34,0x43,0xf6,0xa8,0x88,0x5a,0x30,0x8d,0x31,0x31,0x98,0xa2,0xe0,0x37,0x07,0x11},
	{0x35,0x43,0xf6,0xa8,0x88,0x5a,0x30,0x8d,0x31,0x31,0x98,0xa2,0xe0,0x37,0x07,0x11},
	{0x36,0x43,0xf6,0xa8,0x88,0x5a,0x30,0x8d,0x31,0x31,0x98,0xa2,0xe0,0x37,0x07,0x11},
	{0x37,0x43,0xf6,0xa8,0x88,0x5a,0x30,0x8d,0x31,0x31,0x98,0xa2,0xe0,0x37,0x07,0x11},
	{0x38,0x43,0xf6,0xa8,0x88,0x5a,0x30,0x8d,0x31,0x31,0x98,0xa2,0xe0,0x37,0x07,0x11},
	{0x39,0x43,0xf6,0xa8,0x88,0x5a,0x30,0x8d,0x31,0x31,0x98,0xa2,0xe0,0x37,0x07,0x11},
	{0x3a,0x43,0xf6,0xa8,0x88,0x5a,0x30,0x8d,0x31,0x31,0x98,0xa2,0xe0,0x37,0x07,0x11},
	{0x3b,0x43,0xf6,0xa8,0x88,0x5a,0x30,0x8d,0x31,0x31,0x98,0xa2,0xe0,0x37,0x07,0x11},
};
uint8_t cts[N][16];
uint8_t pt_recon [N][16];

int main() {
	// 1. Load key
	LOAD_BLOCK_TO_REGS(key);
	AES_LOAD_KEY();

	// 2. Start first block
	LOAD_BLOCK_TO_REGS(pts[0]);
	AES_ENC(); // Copies x28-x31 to accel and starts. Regs are now free.

	// 3. Pipeline loop
	for (int i = 1; i < N; i++) {
		// Load NEXT plaintext while accelerator works on CURRENT block.
		LOAD_BLOCK_TO_REGS(pts[i]);

		// Swap: Wait for accel to finish, grab Ciphertext(i - 1), give Plaintext(i)
		AES_ENC_S();

		// Store the results we just retrieved
		STORE_BLOCK_FROM_REGS(cts[i-1]);
	}

	// 4. Drain the pipe (Retrieve last block)
	AES_SYNC(); // Wait for the last block and retrieve it.
	STORE_BLOCK_FROM_REGS(cts[N-1]);

	LOAD_BLOCK_TO_REGS(cts[0]);
	AES_DEC();
	for (int i = 1; i < N; i++) {
		LOAD_BLOCK_TO_REGS(cts[i]);
		AES_DEC_S();
		STORE_BLOCK_FROM_REGS(pt_recon[i-1]);
	}
	AES_SYNC();
	STORE_BLOCK_FROM_REGS(pt_recon[N-1]);

	for (int i = 0; i < N; i++) {
		if (!test_equal(pts[i], pt_recon[i])) {
			printf("Failed\n");
		}
	}
	printf("Success!\n");
	return 0;

}
	



